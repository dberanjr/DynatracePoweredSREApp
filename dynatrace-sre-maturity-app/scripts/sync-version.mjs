// Regenerates ui/app/version.ts from app.config.ts (app.version) plus git
// build metadata (short commit hash) and real build/deploy wall-clock times.
// Wired into the `build`, `start`, and `deploy` npm scripts so the in-app
// version footer and About page always match the deployed app — no manual
// edits needed. Also generates the untracked ui/app/constants.ts from .env so
// customer-specific values (company, app name, tenant URL) never enter git.
import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// app.config.ts is TypeScript, so read the version literal with a regex instead
// of executing it (works on any Node version).
const cfgText = readFileSync(join(root, "app.config.ts"), "utf8");
const version = cfgText.match(/^\s*version:\s*"([^"]+)"/m)?.[1];

if (!version) {
  console.error('[sync-version] could not read app.version from app.config.ts');
  process.exit(1);
}

// ── constants.ts from .env (real env vars win, e.g. in CI) ──
const env = {};
const envFile = join(root, ".env");
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (m) env[m[1]] = m[2].replace(/^(["'])(.*)\1$/, "$2");
  }
} else {
  console.warn("[sync-version] no .env found — using placeholder defaults (copy .env.example to .env)");
}
const setting = (key, fallback) => process.env[key] ?? env[key] ?? fallback;

writeFileSync(
  join(root, "ui/app/constants.ts"),
  `// AUTO-GENERATED by scripts/sync-version.mjs from .env — do not edit or commit.\n` +
    `// App name and environment URL come from @dynatrace-sdk/app-environment at runtime.\n` +
    `export const COMPANY_NAME = ${JSON.stringify(setting("COMPANY_NAME", "YourCompany"))};\n`
);

function git(command, fallback) {
  try {
    return execSync(command, { cwd: root, stdio: ["ignore", "pipe", "ignore"] })
      .toString()
      .trim();
  } catch {
    return fallback;
  }
}

function extractField(text, name) {
  const match = text.match(new RegExp(`export const ${name} = "([^"]*)";`));
  return match ? match[1] : "";
}

const commitHash = git("git rev-parse --short HEAD", "unknown");
const commitDate = git("git log -1 --format=%cI", "");
const nowIso = new Date().toISOString();

const versionFile = join(root, "ui/app/version.ts");
let previousBuildDate = "";
let previousDeployDate = "";
if (existsSync(versionFile)) {
  const prev = readFileSync(versionFile, "utf8");
  previousBuildDate = extractField(prev, "BUILD_DATE");
  previousDeployDate = extractField(prev, "DEPLOY_DATE");
}

// npm sets npm_lifecycle_event to the script name for every process in the
// `npm run X` chain, so this script (invoked from within "build"/"start"/
// "deploy") can tell which one triggered it without any extra plumbing.
const lifecycle = process.env.npm_lifecycle_event;
const isBuildOrDeploy = lifecycle === "build" || lifecycle === "deploy";
const isDeploy = lifecycle === "deploy";

// BUILD_DATE tracks the last real production build (`build`/`deploy`), not a
// local `dev` server start. DEPLOY_DATE only advances on an actual `deploy` —
// both carry the previous value forward otherwise so the About page keeps
// showing the last real build/deploy instead of a dev-session timestamp.
const buildDate = isBuildOrDeploy ? nowIso : previousBuildDate || nowIso;
const deployDate = isDeploy ? nowIso : previousDeployDate;

const out =
  `// AUTO-GENERATED by scripts/sync-version.mjs — do not edit by hand.\n` +
  `// Sourced from app.config.ts (app.version) + git; regenerated on build/deploy.\n` +
  `export const APP_VERSION = ${JSON.stringify(version)};\n` +
  `export const COMMIT_HASH = ${JSON.stringify(commitHash)};\n` +
  `export const COMMIT_DATE = ${JSON.stringify(commitDate)};\n` +
  `export const BUILD_DATE = ${JSON.stringify(buildDate)};\n` +
  `export const DEPLOY_DATE = ${JSON.stringify(deployDate)};\n`;

writeFileSync(versionFile, out);
console.log(
  `[sync-version] ui/app/version.ts -> ${version} · ${commitHash} · build ${buildDate}` +
    (isDeploy ? ` · deployed ${deployDate}` : "")
);
